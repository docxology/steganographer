fn fixture_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("testdata/packets")
}

fn fixture_path(name: &str, extension: &str) -> PathBuf {
    fixture_dir().join(format!("{name}.{extension}"))
}

/// Owner-facing one-command freeze: materializes every golden fixture that is
/// not yet frozen, and treats already-frozen files as an immutability gate
/// (regenerated bytes must match exactly, otherwise this test fails with a
/// drift report).
///
/// Run with:
///
/// ```text
/// cargo test -p steganographer-core --test golden_vectors -- --ignored
/// ```
#[test]
#[ignore = "materializes byte fixtures under testdata/packets/; run with -- --ignored"]
fn materialize_golden_fixtures() {
    let dir = fixture_dir();
    std::fs::create_dir_all(&dir).expect("testdata/packets is creatable");

    for (name, bytes) in fixtures() {
        let hex_text = format!("{}\n", to_hex(&bytes));

        let hex_path = fixture_path(name, "hex");
        if hex_path.exists() {
            let frozen = std::fs::read_to_string(&hex_path).expect("fixture readable");
            assert_eq!(
                frozen.trim(),
                hex_text.trim(),
                "golden vector drift for {name}: regenerated bytes differ from the frozen \
                 fixture. If this change is intentional, delete {name}.hex and re-run this \
                 test to re-freeze, then update manifest.json.",
            );
        } else {
            std::fs::write(&hex_path, &hex_text).expect("fixture file is writable");
            println!("froze {name}.hex ({} bytes)", bytes.len());
        }

        // SHA-256 sidecar so CI can gate fixture hashes without re-running Rust.
        let digest_hex = to_hex(&Sha256::digest(&bytes));
        let sidecar_text = format!("{digest_hex}  {name}.hex\n");
        let sidecar_path = fixture_path(name, "hex.sha256");
        if sidecar_path.exists() {
            let frozen = std::fs::read_to_string(&sidecar_path).expect("sidecar readable");
            assert_eq!(
                frozen.trim(),
                sidecar_text.trim(),
                "SHA-256 sidecar drift for {name}"
            );
        } else {
            std::fs::write(&sidecar_path, &sidecar_text).expect("sidecar file is writable");
        }
    }
}

/// Regular-run drift gate: when fixtures have been frozen by
/// [`materialize_golden_fixtures`], regenerated bytes must match them
/// byte-for-byte. Before the owner freezes fixtures, this passes vacuously.
#[test]
fn frozen_fixtures_match_when_present() {
    let dir = fixture_dir();
    let all = fixtures();
    let frozen: Vec<&(&str, Vec<u8>)> = all
        .iter()
        .filter(|(name, _)| dir.join(format!("{name}.hex")).exists())
        .collect();

    if frozen.is_empty() {
        eprintln!(
            "skipping: no frozen golden fixtures under testdata/packets yet; \
             run `cargo test -p steganographer-core --test golden_vectors -- --ignored` \
             to materialize them"
        );
        return;
    }

    for (name, bytes) in frozen {
        let frozen_hex =
            std::fs::read_to_string(dir.join(format!("{name}.hex"))).expect("fixture readable");
        assert_eq!(
            frozen_hex.trim(),
            to_hex(bytes),
            "golden vector drift for {name}"
        );
        let sidecar = std::fs::read_to_string(dir.join(format!("{name}.hex.sha256")))
            .expect("frozen sidecar readable");
        let digest_hex = to_hex(&Sha256::digest(bytes));
        assert_eq!(
            sidecar.trim(),
            format!("{digest_hex}  {name}.hex"),
            "SHA-256 sidecar drift for {name}"
        );
    }
}

/// Derive `n` deterministic bytes via a BLAKE3 hash chain:
/// `block_0 = BLAKE3(label)`, `block_{i+1} = BLAKE3(block_i)`, concatenated
/// and truncated to `n` bytes.
fn derive_bytes(label: &[u8], n: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(n + 32);
    let mut current = blake3::hash(label);
    while out.len() < n {
        out.extend_from_slice(current.as_bytes());
        current = blake3::hash(current.as_bytes());
    }
    out.truncate(n);
    out
}

/// 16-byte packet identifier for a vector:
/// `BLAKE3(b"golden packet-id: " ++ name)[..16]`.
fn packet_id_for(name: &str) -> [u8; 16] {
    let mut label = b"golden packet-id: ".to_vec();
    label.extend_from_slice(name.as_bytes());
    let hash = blake3::hash(&label);
    let mut id = [0u8; 16];
    id.copy_from_slice(&hash.as_bytes()[..16]);
    id
}

/// 8-byte public locator nonce for a vector:
/// `BLAKE3(b"golden locator-nonce: " ++ name)[..8]`.
fn locator_nonce_for(name: &str) -> [u8; 8] {
    let mut label = b"golden locator-nonce: ".to_vec();
    label.extend_from_slice(name.as_bytes());
    let hash = blake3::hash(&label);
    let mut nonce = [0u8; 8];
    nonce.copy_from_slice(&hash.as_bytes()[..8]);
    nonce
}

/// Synthetic byte carrier: `derive_bytes(b"golden carrier: " ++ name, units)`.
fn synthetic_carrier(name: &str, units: usize) -> Vec<u8> {
    let mut label = b"golden carrier: ".to_vec();
    label.extend_from_slice(name.as_bytes());
    derive_bytes(&label, units)
}

/// The spatial-LSB kernel descriptor shared by every vector: algorithm 1
/// (`KERNEL_SPATIAL_LSB`), version 1, parameters `[1]` (1 bit per unit).
fn kernel_descriptor() -> AlgorithmDescriptor {
    AlgorithmDescriptor::new(KERNEL_SPATIAL_LSB, 1, vec![1])
}

/// Replicate `encryption::derive_nonce`: `BLAKE3(salt || packet_id)[..12]`.
fn derive_aead_nonce(salt: &[u8; 4], packet_id: &[u8; 16]) -> [u8; 12] {
    let mut hasher = blake3::Hasher::new();
    hasher.update(salt);
    hasher.update(packet_id);
    let hash = hasher.finalize();
    let mut nonce = [0u8; 12];
    nonce.copy_from_slice(&hash.as_bytes()[..12]);
    nonce
}

/// The AEAD associated data used by `transforms.rs`: packet identity binding
/// (`packet_id || payload_kind u16 BE || original_len u64 BE`).
fn transform_aad(ctx: &TransformContext<'_>) -> Vec<u8> {
    let mut aad = Vec::with_capacity(26);
    aad.extend_from_slice(ctx.packet_id);
    aad.extend_from_slice(&ctx.payload_kind.to_be_bytes());
    aad.extend_from_slice(&ctx.original_len.to_be_bytes());
    aad
}

/// Assemble a transformed generic packet: an envelope whose digest covers the
/// *logical* payload plus the recorded transform descriptors, the encoded
/// (transformed) body, and a locator carrying the mirroring flag bits.
#[allow(clippy::too_many_arguments)] // test-vector builder mirrors the packet shape
fn transformed_packet(
    logical_payload: &[u8],
    packet_id: [u8; 16],
    payload_kind: PayloadKind,
    transforms: Vec<TransformDescriptor>,
    body: Vec<u8>,
    flags: u16,
    placement: AlgorithmDescriptor,
    locator_nonce: [u8; 8],
) -> GenericPacket {
    let mut envelope = PacketEnvelope::for_payload(
        packet_id,
        payload_kind,
        logical_payload,
        placement,
        kernel_descriptor(),
    );
    envelope.transforms = transforms;
    let envelope_bytes = envelope.encode(&LIMITS).expect("envelope encodes");
    let locator = Locator::new(
        flags,
        envelope_bytes.len(),
        body.len(),
        crc32c(&envelope_bytes),
        locator_nonce,
        &LIMITS,
    )
    .expect("locator fits limits");
    GenericPacket {
        locator,
        envelope,
        body,
    }
}

fn to_hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

// ---------------------------------------------------------------------------
// Shared invariant assertions
// ---------------------------------------------------------------------------

/// Core invariants every vector must satisfy:
///
/// 1. encode is deterministic (encode twice → identical bytes);
/// 2. the locator prefix is exactly `STG3` + protocol `1.0`;
/// 3. encoded length matches the locator's own accounting;
/// 4. decode(encoded) == packet, and decode→encode is byte-exact;
/// 5. the envelope TLV stream opens with the canonical critical field ids;
/// 6. the BLAKE3 content digest verifies against the logical payload.
fn assert_packet_invariants(packet: &GenericPacket, logical_payload: &[u8]) {
    let encoded = packet.encode(&LIMITS).expect("packet encodes");
    let again = packet.encode(&LIMITS).expect("packet re-encodes");
    assert_eq!(
        encoded, again,
        "encode must be deterministic (twice-identical bytes)"
    );

    // Known-length locator prefix, hand-computable from the spec.
    assert_eq!(encoded[..4], PACKET_MAGIC, "locator magic must be STG3");
    assert_eq!(encoded[4], PROTOCOL_MAJOR);
    assert_eq!(encoded[5], PROTOCOL_MINOR);
    let envelope_len = packet.locator.envelope_len as usize;
    assert_eq!(
        encoded.len(),
        LOCATOR_SIZE + envelope_len + packet.body.len(),
        "encoded length must equal locator + envelope + body"
    );

    // Decode round-trip, and canonical re-encode must be byte-exact.
    let decoded = GenericPacket::decode(&encoded, &LIMITS).expect("packet decodes");
    assert_eq!(&decoded, packet, "decode(encode(x)) must equal x");
    let reencoded = decoded.encode(&LIMITS).expect("decoded packet re-encodes");
    assert_eq!(
        reencoded, encoded,
        "decode→encode must round-trip byte-exact"
    );

    // Canonical envelope opening, hand-computable: critical packet-id TLV
    // (wire id 0x8001, 16-byte value), then the packet identifier itself.
    assert_eq!(
        &encoded[LOCATOR_SIZE..LOCATOR_SIZE + 6],
        &[0x80, 0x01, 0x00, 0x00, 0x00, 0x10],
        "first envelope field must be the critical 16-byte packet-id TLV"
    );
    assert_eq!(
        &encoded[LOCATOR_SIZE + 6..LOCATOR_SIZE + 22],
        &packet.envelope.packet_id[..],
        "packet-id TLV value must be the packet identifier"
    );
    let ids = envelope_wire_ids(&encoded, envelope_len);
    assert_eq!(
        &ids[..4],
        &[0x8001, 0x8002, 0x8003, 0x8004],
        "envelope must open with packet-id, payload-kind, original-length, content-digest"
    );
    assert!(
        ids.contains(&0x8006),
        "placement descriptor must be present"
    );
    assert!(ids.contains(&0x8007), "kernel descriptor must be present");
    assert!(ids.contains(&0x8008), "created-version must be present");

    assert!(
        packet.envelope.content_digest.verify(logical_payload),
        "BLAKE3 content digest must verify against the logical payload"
    );
}

/// Walk the envelope TLV headers and return the raw wire field identifiers
/// (critical bit included). The walk must consume the envelope exactly.
fn envelope_wire_ids(packet_bytes: &[u8], envelope_len: usize) -> Vec<u16> {
    let mut ids = Vec::new();
    let mut cursor = LOCATOR_SIZE;
    let end = LOCATOR_SIZE + envelope_len;
    while cursor < end {
        assert!(cursor + 6 <= end, "TLV header runs past the envelope");
        let raw = u16::from_be_bytes([packet_bytes[cursor], packet_bytes[cursor + 1]]);
        let len = u32::from_be_bytes([
            packet_bytes[cursor + 2],
            packet_bytes[cursor + 3],
            packet_bytes[cursor + 4],
            packet_bytes[cursor + 5],
        ]) as usize;
        assert!(cursor + 6 + len <= end, "TLV value runs past the envelope");
        ids.push(raw);
        cursor += 6 + len;
    }
    assert_eq!(cursor, end, "TLV walk must consume the envelope exactly");
    ids
}

/// `FLAG_ENCRYPTED` / `FLAG_PAYLOAD_SIGNED` must mirror the AEAD / signature
/// transform descriptors exactly: zeroing the flags on a transformed packet
/// must fail closed on encode.
fn assert_flag_transform_coupling(packet: &GenericPacket) {
    let mut broken = packet.clone();
    broken.locator.flags = 0;
    assert!(
        broken.encode(&LIMITS).is_err(),
        "locator flags must not be detachable from recorded transforms"
    );
}


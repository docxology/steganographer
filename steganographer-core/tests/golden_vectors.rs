#[test]
fn vector_01_untransformed_sequential_invariants() {
    let packet = vector_01_untransformed_sequential();
    let payload = derive_bytes(b"golden payload: vector-01", 64);
    assert_packet_invariants(&packet, &payload);

    // Untransformed: body is the payload verbatim, no flags, no transforms.
    assert_eq!(packet.body, payload);
    assert_eq!(packet.locator.flags, 0);
    assert!(packet.envelope.transforms.is_empty());
    assert_eq!(
        packet.envelope.placement.algorithm, PLACEMENT_SEQUENTIAL,
        "vector declares sequential placement (1)"
    );

    // The same packet also embeds and extracts through the plain sequential
    // spatial-LSB carrier (descriptor 1, no keyed flag).
    let config = EmbeddingConfig { bits_per_unit: 1 };
    let packet_bytes = packet.encode(&LIMITS).expect("encodes");
    let mut carrier = synthetic_carrier("vector-01", CARRIER_UNITS);
    SpatialLsb
        .embed_packet(&mut carrier, &packet_bytes, &config)
        .expect("sequential embedding fits");
    let extracted = SpatialLsb
        .extract_packet(&carrier, &config, &LIMITS)
        .expect("sequential extraction succeeds");
    assert_eq!(extracted.packet, packet);
}


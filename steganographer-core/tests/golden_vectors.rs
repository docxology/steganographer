/// (b) AEAD-encrypted packet with a pinned salt.
///
/// Derivation:
/// - payload = `derive_bytes(b"golden payload: vector-02", 72)`
/// - packet_id / locator nonce derived from the vector name
/// - key = `EncryptionKey(0x77 × 32)` (documented test key)
/// - AEAD salt pinned to `a5 5a 5a a5`;
///   nonce = `BLAKE3(salt || packet_id)[..12]`
/// - AAD = `packet_id || payload_kind(u16 BE) || original_len(u64 BE)`
/// - body = `salt(4) || ChaCha20-Poly1305-Seal(key, nonce, payload, aad)`
/// - placement `(PLACEMENT_SEQUENTIAL=1, v1, no params)`, flags `0x0002`
///
/// The deterministic construction replicates `encryption::encrypt` with a
/// pinned salt and is cross-checked against the crate below.
fn vector_02_encrypted_aead() -> GenericPacket {
    let payload = derive_bytes(b"golden payload: vector-02", 72);
    let packet_id = packet_id_for("vector-02");
    let payload_kind = PayloadKind::Bytes;
    let ctx = TransformContext {
        packet_id: &packet_id,
        payload_kind: payload_kind as u16,
        original_len: payload.len() as u64,
    };
    let aad = transform_aad(&ctx);
    let key = EncryptionKey::from_bytes(&ENCRYPTION_TEST_KEY);

    let (descriptors, flags) = {
        let (_, descriptors, flags) = transforms::apply(
            &payload,
            &ctx,
            None,
            false,
            Some(&key),
            0,
            DEFAULT_ECC_CHUNK_LEN,
        )
        .expect("AEAD transform applies");
        assert_eq!(descriptors.len(), 1);
        assert_eq!(descriptors[0].algorithm, TRANSFORM_AEAD_CHACHA20_POLY1305);
        assert_eq!(descriptors[0].parameters, Vec::<u8>::new());
        assert_eq!(flags, FLAG_ENCRYPTED);
        (descriptors, flags)
    };

    // Deterministic body: pin the salt, seal with the documented nonce.
    let cipher = ChaCha20Poly1305::new_from_slice(&ENCRYPTION_TEST_KEY).expect("32-byte key");
    let nonce = derive_aead_nonce(&FIXED_AEAD_SALT, &packet_id);
    let mut body = FIXED_AEAD_SALT.to_vec();
    body.extend_from_slice(
        &cipher
            .encrypt(
                Nonce::from_slice(&nonce),
                Payload {
                    msg: &payload,
                    aad: &aad,
                },
            )
            .expect("AEAD seal succeeds"),
    );
    assert_eq!(body.len(), 4 + payload.len() + 16);

    // Cross-check 1: the crate's decrypt accepts the pinned-salt body and the
    // documented AAD, recovering the payload.
    assert_eq!(
        encryption::decrypt(&key, &packet_id, &body, Some(&aad)).expect("crate decrypts"),
        payload,
        "pinned-salt body must decrypt under the documented derivation"
    );
    // Cross-check 2: a fresh crate-side encryption (random salt) must derive
    // its nonce with the exact same formula — reconstruct and decrypt it.
    let fresh = encryption::encrypt(&key, &packet_id, &payload, Some(&aad))
        .expect("crate-side encryption works");
    let fresh_salt: [u8; 4] = fresh[..4].try_into().expect("salt slice");
    let fresh_nonce = derive_aead_nonce(&fresh_salt, &packet_id);
    let recovered = ChaCha20Poly1305::new_from_slice(&ENCRYPTION_TEST_KEY)
        .expect("32-byte key")
        .decrypt(
            Nonce::from_slice(&fresh_nonce),
            Payload {
                msg: &fresh[4..],
                aad: &aad,
            },
        )
        .expect("crate salt must reconstruct the nonce via BLAKE3(salt||packet_id)[..12]");
    assert_eq!(recovered, payload);

    transformed_packet(
        &payload,
        packet_id,
        payload_kind,
        descriptors,
        body,
        flags,
        AlgorithmDescriptor::new(PLACEMENT_SEQUENTIAL, 1, Vec::new()),
        locator_nonce_for("vector-02"),
    )
}

/// (c) Keyed placement (PLC-002) over a synthetic carrier.
///
/// Derivation:
/// - payload = `derive_bytes(b"golden payload: vector-03", 80)`
/// - packet_id / locator nonce derived from the vector name
/// - placement `(PLACEMENT_KEYED=2, v1, no params)`, kernel `(1, v1, [1])`
/// - locator flags `0x0008` (`FLAG_KEYED_LOCATOR`)
/// - carrier = `derive_bytes(b"golden carrier: vector-03", 4096)`
/// - embedding key `0x2c` × 32; 1 bit per unit; the 8-byte keyed recognition
///   tag occupies the first 64 canonical units and packet bits land at
///   `KeyedPermutation` positions over the remaining 4032 units.
fn vector_03_keyed_placement() -> (GenericPacket, Vec<u8>) {
    let payload = derive_bytes(b"golden payload: vector-03", 80);
    let packet = GenericPacket::new_untransformed(
        payload,
        packet_id_for("vector-03"),
        locator_nonce_for("vector-03"),
        PayloadKind::Bytes,
        AlgorithmDescriptor::new(PLACEMENT_KEYED, 1, Vec::new()),
        kernel_descriptor(),
        &LIMITS,
    )
    .expect("keyed packet builds");

    // The keyed locator flag is deliberately not inferable by the builder;
    // the caller sets it on the locator, mirroring the carrier contract
    // ("the caller sets FLAG_KEYED_LOCATOR and PLACEMENT_KEYED").
    let mut packet = packet;
    packet.locator.flags = FLAG_KEYED_LOCATOR;

    let config = EmbeddingConfig { bits_per_unit: 1 };
    let packet_bytes = packet.encode(&LIMITS).expect("packet encodes");
    let mut carrier = synthetic_carrier("vector-03", CARRIER_UNITS);
    let report = KeyedSpatialLsb::new(KEYED_PLACEMENT_EMBEDDING_KEY)
        .embed_packet(&mut carrier, &packet_bytes, &config)
        .expect("keyed embedding fits");
    assert_eq!(report.packet_bytes, packet_bytes.len());
    (packet, carrier)
}


//! Alpha golden-vector corpus for generic packets, transforms, and keyed
//! placement (QUA-003 partial; roadmap v0.7.0 "Freeze immutable packet and
//! placement vectors").
//!
//! # STATUS: stable (owner-approved 2026-09-21)
//!
//! Every vector here is **generated deterministically by the test itself**
//! from fixed, documented seeds, keys, packet identifiers, and nonce
//! derivations — see the "Derivation" doc comment on each vector builder and
//! `testdata/packets/manifest.json`. The assertions check *internal
//! invariants* (deterministic encode, decode round-trip, known locator and
//! envelope prefixes, flag⇔transform coupling, keyed-carrier stealth) rather
//! than frozen bytes, so the suite passes before any byte fixture exists.
//!
//! Byte-level frozen fixtures are materialized by the owner in one command:
//!
//! cargo test -p steganographer-core --test golden_vectors -- --ignored
//! ```
//!
//! That run writes `<vector>.hex` files (plus `<vector>.hex.sha256` sidecars)
//! under `testdata/packets/`. Once frozen, every regular run (including CI,
//! via [`frozen_fixtures_match_when_present`]) compares regenerated bytes
//! against the frozen fixtures and fails on drift, per spec 05
//! ("schema and golden-vector immutability", "corpus manifest/hash validation").


/// (e) DEFLATE compression + Ed25519 payload signature (sign → compress order).
///
/// Derivation:
/// - payload = `b"alpha-provisional golden vector; "` × 6 = 198 bytes
/// - packet_id / locator nonce derived from the vector name
/// - signing seed = `0x33` × 32 (Ed25519, documented test key)
/// - `transforms::apply(sign, compress)`: sign the logical payload first, then
///   DEFLATE-compress (recorded only because it shrinks)
/// - flags `0x0011` (`FLAG_PAYLOAD_SIGNED | FLAG_COMPRESSED`), body = deflate
///   stream; placement `(PLACEMENT_SEQUENTIAL=1, v1, no params)`
fn vector_05_deflate_sign() -> GenericPacket {
    const UNIT: &[u8] = b"alpha-provisional golden vector; ";
    let payload: Vec<u8> = UNIT.iter().cycle().take(198).copied().collect();
    let packet_id = packet_id_for("vector-05");
    let payload_kind = PayloadKind::Text;
    let ctx = TransformContext {
        packet_id: &packet_id,
        payload_kind: payload_kind as u16,
        original_len: payload.len() as u64,
    };
    let signing_key = SigningKey::from_bytes(&SIGNING_TEST_SEED);

    let (body, descriptors, flags) = transforms::apply(
        &payload,
        &ctx,
        Some(&signing_key),
        true,
        None,
        0,
        DEFAULT_ECC_CHUNK_LEN,
    )
    .expect("sign+compress transforms apply");

    assert_eq!(flags, FLAG_PAYLOAD_SIGNED | FLAG_COMPRESSED);
    assert_eq!(descriptors.len(), 2);
    assert_eq!(
        descriptors[0].algorithm, TRANSFORM_PAYLOAD_SIGN_ED25519,
        "signing is applied first"
    );
    assert_eq!(
        descriptors[1].algorithm, TRANSFORM_COMPRESS_DEFLATE,
        "compression is applied second"
    );
    assert_eq!(descriptors[1].parameters, Vec::<u8>::new());
    assert!(
        body.len() < payload.len(),
        "DEFLATE must shrink the repeating payload"
    );

    transformed_packet(
        &payload,
        packet_id,
        payload_kind,
        descriptors,
        body,
        flags,
        AlgorithmDescriptor::new(PLACEMENT_SEQUENTIAL, 1, Vec::new()),
        locator_nonce_for("vector-05"),
    )
}

